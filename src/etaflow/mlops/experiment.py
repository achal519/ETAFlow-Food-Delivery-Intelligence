"""ETAFlow Experiment Tracking Module using MLflow.

In simple terms for students:
------------------------------
Think of MLflow as a digital "lab notebook" for machine learning experiments:
1. Experiment: A project notebook where all related tests are collected
   (e.g., 'etaflow-delivery-intelligence').
2. Run: A single page in that notebook corresponding to one trained model
   (e.g., 'baseline-dummy', 'linear-ridge', or 'champion-random-forest').
3. Parameters: The configuration settings you gave the model before training
   (e.g., number of trees = 100, max tree depth = 16).
4. Metrics: The quantitative test scores measured after training
   (e.g., MAE in minutes, RMSE in minutes, R^2 score).
5. Artifacts: Any output files generated by the run, such as the serialized
   model (.joblib) or feature importance charts.
6. Tags: Key-value labels used to filter and organize runs
   (e.g., stage='Production', version='v1.0.0', algorithm='RandomForest').
"""

import os
from datetime import datetime, timezone
import json
from pathlib import Path
from typing import Any, Dict, List, Optional
import mlflow
from mlflow.entities import Run
from mlflow.tracking import MlflowClient

# Ensure file-store fallback works and silence agent hints
os.environ.setdefault("MLFLOW_ALLOW_FILE_STORE", "true")
os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")


class ExperimentTracker:
    """Manages MLflow experiment lifecycle, run logging, and summary reporting."""

    def __init__(
        self,
        experiment_name: str = "etaflow-delivery-intelligence",
        tracking_uri: Optional[str] = None,
        artifact_location: Optional[str] = None,
    ) -> None:
        """Initialize experiment tracker.

        Args:
            experiment_name: Logical group name for related runs.
            tracking_uri: MLflow backend URI. Defaults to local SQLite database 'sqlite:///mlflow.db'.
            artifact_location: Optional directory path to store artifacts.
        """
        self.experiment_name = experiment_name
        self.tracking_uri = tracking_uri or "sqlite:///mlflow.db"
        self.artifact_location = artifact_location or str(Path("mlartifacts").resolve().as_uri())

        mlflow.set_tracking_uri(self.tracking_uri)
        self.client = MlflowClient(tracking_uri=self.tracking_uri)
        self.experiment_id = self._get_or_create_experiment()

    def _get_or_create_experiment(self) -> str:
        """Fetch existing experiment ID or create a new experiment."""
        exp = self.client.get_experiment_by_name(self.experiment_name)
        if exp is not None:
            return exp.experiment_id
        return self.client.create_experiment(
            name=self.experiment_name,
            artifact_location=self.artifact_location,
        )

    def log_run(
        self,
        run_name: str,
        parameters: Dict[str, Any],
        metrics: Dict[str, float],
        tags: Optional[Dict[str, str]] = None,
        artifact_paths: Optional[List[Path]] = None,
    ) -> str:
        """Log a complete experiment run to MLflow.

        Args:
            run_name: Human-friendly name for this run (e.g. 'champion-random-forest').
            parameters: Model settings (hyperparameters).
            metrics: Test evaluation scores (MAE, RMSE, R2, MAPE).
            tags: Descriptive labels (version, stage, model_type).
            artifact_paths: Paths to files to store alongside this run.

        Returns:
            The unique MLflow run_id string.
        """
        all_tags = {
            "mlflow.runName": run_name,
            "logged_at_utc": datetime.now(timezone.utc).isoformat(),
        }
        if tags:
            all_tags.update(tags)

        with mlflow.start_run(
            experiment_id=self.experiment_id,
            run_name=run_name,
        ) as active_run:
            # 1. Log tags
            for key, val in all_tags.items():
                mlflow.set_tag(key, str(val))

            # 2. Log hyperparameters
            for param_key, param_val in parameters.items():
                mlflow.log_param(param_key, param_val)

            # 3. Log test evaluation metrics
            for metric_key, metric_val in metrics.items():
                mlflow.log_metric(metric_key, float(metric_val))

            # 4. Log artifacts (model files, reports) without modifying originals
            if artifact_paths:
                for art_path in artifact_paths:
                    if Path(art_path).exists():
                        mlflow.log_artifact(str(art_path))

            run_id = active_run.info.run_id

        return run_id

    def get_runs_summary(self) -> List[Dict[str, Any]]:
        """Fetch all logged runs under this experiment formatted as clean dictionaries.

        Returns:
            List of run summaries sorted chronologically by start time.
        """
        runs: List[Run] = self.client.search_runs(
            experiment_ids=[self.experiment_id],
            order_by=["attribute.start_time ASC"],
        )

        summaries = []
        for run in runs:
            data = run.data
            info = run.info
            summaries.append({
                "run_id": info.run_id,
                "run_name": data.tags.get("mlflow.runName", info.run_id),
                "status": info.status,
                "start_time": datetime.fromtimestamp(info.start_time / 1000, tz=timezone.utc).isoformat(),
                "model_type": data.tags.get("model_type", "Unknown"),
                "version": data.tags.get("version", ""),
                "stage": data.tags.get("stage", "Candidate"),
                "parameters": data.params,
                "metrics": {k: round(v, 4) for k, v in data.metrics.items()},
                "artifact_uri": info.artifact_uri,
            })
        return summaries

    def export_summary_json(self, output_path: str = "reports/experiments/experiment_summary.json") -> Path:
        """Export experiment runs to a structured JSON file for dashboards and reports.

        Args:
            output_path: Target destination path for the JSON report.

        Returns:
            Resolved Path of the saved report.
        """
        dest = Path(output_path)
        dest.parent.mkdir(parents=True, exist_ok=True)

        runs_summary = self.get_runs_summary()
        payload = {
            "experiment_name": self.experiment_name,
            "experiment_id": self.experiment_id,
            "tracking_uri": self.tracking_uri,
            "total_runs": len(runs_summary),
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
            "runs": runs_summary,
        }

        with open(dest, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)

        return dest
