"""Data and Prediction Drift Monitoring Module for ETAFlow.

In simple terms for students:
------------------------------
When an ML model is deployed in production, real-world conditions change over time:
1. Feature Drift (Data Drift):
   - The input data entering the model changes compared to what the model saw during training.
   - Example: Sudden heavy monsoon rains cause delivery distances and traffic conditions
     to spike significantly.
2. Prediction Drift (Concept / Output Drift):
   - The outputs generated by the model shift away from the training baseline distribution.
   - Example: The model starts constantly predicting 45-minute ETAs instead of 25-minute ETAs.

How we detect drift mathematically:
1. Population Stability Index (PSI):
   - Measures how much a variable's distribution has shifted between a reference (baseline)
     and a current dataset.
   - Formula: PSI = Sum_i (Q_i - P_i) * ln(Q_i / P_i)
   - Interpretation:
     - PSI < 0.10: Stable (no significant distribution change).
     - 0.10 <= PSI < 0.20: Moderate shift (warning / investigate).
     - PSI >= 0.20: Significant drift (alert / model retraining needed).

2. Kolmogorov-Smirnov (KS) Test (for continuous numeric features):
   - Compares the empirical cumulative distributions of two samples.
   - Output: KS statistic D and p-value.
   - If p-value < 0.05, we reject the null hypothesis that both samples come from the same
     distribution (statistically significant shift).

3. Chi-Square (chi^2) Goodness-of-Fit Test (for categorical features):
   - Compares observed category counts in the current batch against expected counts from
     the baseline reference proportions.
   - If p-value < 0.05, the category proportions have shifted significantly.
"""

from datetime import datetime, timezone
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union
import numpy as np
import pandas as pd
import scipy.stats as stats


def compute_numeric_psi(
    reference: Union[np.ndarray, pd.Series, List[float]],
    target: Union[np.ndarray, pd.Series, List[float]],
    num_bins: int = 10,
    epsilon: float = 1e-4,
) -> float:
    """Calculate Population Stability Index (PSI) across numeric distributions.

    Args:
        reference: Reference baseline array (e.g. training set feature).
        target: Current observation array (e.g. incoming production batch).
        num_bins: Number of bins to evaluate (default 10).
        epsilon: Small smoothing constant to prevent division or logarithm of zero.

    Returns:
        PSI float value.
    """
    ref = np.asarray(reference, dtype=float)
    tar = np.asarray(target, dtype=float)

    ref = ref[np.isfinite(ref)]
    tar = tar[np.isfinite(tar)]

    if len(ref) == 0 or len(tar) == 0:
        return 0.0

    min_val = min(float(ref.min()), float(tar.min()))
    max_val = max(float(ref.max()), float(tar.max()))
    if min_val == max_val:
        return 0.0

    bin_edges = np.linspace(min_val - 1e-4, max_val + 1e-4, num_bins + 1)
    ref_counts, _ = np.histogram(ref, bins=bin_edges)
    tar_counts, _ = np.histogram(tar, bins=bin_edges)

    k = len(ref_counts)
    ref_pct = (ref_counts + epsilon) / (len(ref) + epsilon * k)
    tar_pct = (tar_counts + epsilon) / (len(tar) + epsilon * k)

    psi_val = np.sum((tar_pct - ref_pct) * np.log(tar_pct / ref_pct))
    return float(max(0.0, psi_val))


def compute_categorical_psi(
    reference_counts: Dict[str, int],
    target_counts: Dict[str, int],
    epsilon: float = 1e-4,
) -> float:
    """Calculate Population Stability Index (PSI) for categorical features.

    Args:
        reference_counts: Dict mapping category -> count in baseline reference.
        target_counts: Dict mapping category -> count in current target batch.
        epsilon: Smoothing constant.

    Returns:
        Categorical PSI value.
    """
    all_categories = sorted(list(set(reference_counts.keys()).union(set(target_counts.keys()))))
    total_ref = max(1, sum(reference_counts.values()))
    total_tar = max(1, sum(target_counts.values()))
    k = len(all_categories)

    ref_pct = np.array([
        (reference_counts.get(cat, 0) + epsilon) / (total_ref + epsilon * k)
        for cat in all_categories
    ])
    tar_pct = np.array([
        (target_counts.get(cat, 0) + epsilon) / (total_tar + epsilon * k)
        for cat in all_categories
    ])

    psi_val = np.sum((tar_pct - ref_pct) * np.log(tar_pct / ref_pct))
    return float(max(0.0, psi_val))


def compute_ks_test(
    reference: Union[np.ndarray, pd.Series, List[float]],
    target: Union[np.ndarray, pd.Series, List[float]],
) -> Dict[str, float]:
    """Perform Kolmogorov-Smirnov 2-sample test for continuous distributions.

    Args:
        reference: Reference baseline array.
        target: Current observation array.

    Returns:
        Dict containing statistic (D) and p_value.
    """
    ref = np.asarray(reference, dtype=float)
    tar = np.asarray(target, dtype=float)

    ref = ref[np.isfinite(ref)]
    tar = tar[np.isfinite(tar)]

    if len(ref) == 0 or len(tar) == 0:
        return {"statistic": 0.0, "p_value": 1.0}

    res = stats.ks_2samp(ref, tar)
    return {
        "statistic": round(float(res.statistic), 5),
        "p_value": float(res.pvalue),
    }


def compute_chi2_test(
    reference_counts: Dict[str, int],
    target_counts: Dict[str, int],
) -> Dict[str, float]:
    """Perform Chi-Square goodness-of-fit test for categorical frequencies.

    Args:
        reference_counts: Category counts in reference baseline.
        target_counts: Category counts in current target batch.

    Returns:
        Dict containing chi2_statistic, p_value, and degrees of freedom.
    """
    all_categories = sorted(list(set(reference_counts.keys()).union(set(target_counts.keys()))))
    total_ref = max(1, sum(reference_counts.values()))
    total_tar = max(1, sum(target_counts.values()))

    # Calculate expected frequencies normalized exactly to target total
    observed = []
    expected = []
    for cat in all_categories:
        ref_p = reference_counts.get(cat, 0) / total_ref
        exp_count = ref_p * total_tar
        obs_count = target_counts.get(cat, 0)
        expected.append(max(1e-4, exp_count))
        observed.append(float(obs_count))

    obs_arr = np.array(observed, dtype=float)
    exp_arr = np.array(expected, dtype=float)
    # Ensure exact match in sums to satisfy scipy tolerance
    exp_arr = exp_arr * (obs_arr.sum() / exp_arr.sum())

    res = stats.chisquare(f_obs=obs_arr, f_exp=exp_arr)
    return {
        "statistic": round(float(res.statistic), 4),
        "p_value": float(res.pvalue),
        "degrees_of_freedom": max(1, len(all_categories) - 1),
    }


class DriftDetector:
    """Manages baseline reference distributions and evaluates batch drift."""

    def __init__(
        self,
        reference_stats: Optional[Dict[str, Any]] = None,
        psi_warning: float = 0.10,
        psi_alert: float = 0.20,
        p_value_threshold: float = 0.05,
    ) -> None:
        """Initialize DriftDetector with reference metrics and drift thresholds.

        Args:
            reference_stats: Precalculated baseline reference statistics dictionary.
            psi_warning: Threshold for moderate shift warning (default 0.10).
            psi_alert: Threshold for significant drift alert (default 0.20).
            p_value_threshold: Significance level alpha for statistical tests (default 0.05).
        """
        self.reference_stats = reference_stats or {}
        self.psi_warning = psi_warning
        self.psi_alert = psi_alert
        self.p_value_threshold = p_value_threshold

    @classmethod
    def fit_reference(
        cls,
        df: pd.DataFrame,
        numeric_columns: List[str],
        categorical_columns: List[str],
        dataset_fingerprint: str = "",
        model: Optional[Any] = None,
        sample_size_distribution: int = 5000,
    ) -> "DriftDetector":
        """Compute baseline distribution statistics directly from reference training DataFrame.

        Args:
            df: Training dataset (e.g. train_features.csv).
            numeric_columns: Names of continuous features.
            categorical_columns: Names of categorical / binary one-hot features.
            dataset_fingerprint: SHA-256 hash of source dataset for provenance.
            model: Optional trained model to compute baseline prediction distribution.
            sample_size_distribution: Sample size to store for distribution testing.

        Returns:
            Initialized DriftDetector instance with reference statistics.
        """
        stats_dict: Dict[str, Any] = {
            "created_at_utc": datetime.now(timezone.utc).isoformat(),
            "dataset_fingerprint": dataset_fingerprint,
            "total_rows": len(df),
            "numeric_features": {},
            "categorical_features": {},
            "prediction_stats": {},
        }

        sample_n = min(len(df), sample_size_distribution)
        sampled_df = df.sample(n=sample_n, random_state=42)

        for col in numeric_columns:
            if col in df.columns:
                vals = df[col].dropna().values
                stats_dict["numeric_features"][col] = {
                    "mean": round(float(np.mean(vals)), 4),
                    "std": round(float(np.std(vals)), 4),
                    "min": round(float(np.min(vals)), 4),
                    "max": round(float(np.max(vals)), 4),
                    "p25": round(float(np.percentile(vals, 25)), 4),
                    "p50": round(float(np.percentile(vals, 50)), 4),
                    "p75": round(float(np.percentile(vals, 75)), 4),
                    "sample_distribution": sampled_df[col].dropna().tolist(),
                }

        for col in categorical_columns:
            if col in df.columns:
                counts = df[col].value_counts().to_dict()
                str_counts = {str(k): int(v) for k, v in counts.items()}
                stats_dict["categorical_features"][col] = {
                    "counts": str_counts,
                    "total": sum(str_counts.values()),
                }

        if model is not None:
            try:
                preds = model.predict(sampled_df)
                stats_dict["prediction_stats"] = {
                    "mean": round(float(np.mean(preds)), 4),
                    "std": round(float(np.std(preds)), 4),
                    "min": round(float(np.min(preds)), 4),
                    "max": round(float(np.max(preds)), 4),
                    "sample_distribution": [float(p) for p in preds],
                }
            except Exception:
                pass

        return cls(reference_stats=stats_dict)

    def evaluate_batch(
        self,
        batch_df: pd.DataFrame,
        batch_label: str = "current_batch",
        is_synthetic: bool = False,
        model: Optional[Any] = None,
    ) -> Dict[str, Any]:
        """Evaluate a test batch against reference distributions for feature and prediction drift.

        Args:
            batch_df: Dataframe of current observations.
            batch_label: Human-readable name for this batch.
            is_synthetic: Boolean flag indicating if data was synthetically generated.
            model: Optional trained model to evaluate prediction output drift.

        Returns:
            Dictionary containing detailed drift metrics, test p-values, PSI values, and overall alert status.
        """
        feature_reports: Dict[str, Any] = {}
        drifted_count = 0
        warning_count = 0

        num_refs = self.reference_stats.get("numeric_features", {})
        cat_refs = self.reference_stats.get("categorical_features", {})

        # 1. Evaluate Numeric Features (Continuous PSI + KS Test)
        for col, ref_info in num_refs.items():
            if col not in batch_df.columns:
                continue

            ref_samples = np.array(ref_info["sample_distribution"])
            tar_vals = batch_df[col].dropna().values

            psi_score = compute_numeric_psi(ref_samples, tar_vals)
            ks_res = compute_ks_test(ref_samples, tar_vals)

            # Industry-standard MLOps alerting:
            # - ALERT: Significant shift (PSI >= 0.20) OR (PSI >= 0.10 with high statistical confidence p < alpha)
            # - WARNING: Moderate shift (PSI >= 0.10)
            # - STABLE: Normal operational variation (PSI < 0.10)
            drift_status = "STABLE"
            if psi_score >= self.psi_alert:
                drift_status = "ALERT"
                drifted_count += 1
            elif psi_score >= self.psi_warning and ks_res["p_value"] < self.p_value_threshold:
                drift_status = "ALERT"
                drifted_count += 1
            elif psi_score >= self.psi_warning:
                drift_status = "WARNING"
                warning_count += 1

            feature_reports[col] = {
                "feature_type": "numeric",
                "psi": round(psi_score, 4),
                "test_applied": "kolmogorov_smirnov",
                "ks_statistic": ks_res["statistic"],
                "p_value": ks_res["p_value"],
                "status": drift_status,
                "current_mean": round(float(np.mean(tar_vals)), 4),
                "reference_mean": ref_info["mean"],
            }

        # 2. Evaluate Categorical Features (Categorical PSI + Chi-Square Test)
        for col, ref_info in cat_refs.items():
            if col not in batch_df.columns:
                continue

            ref_counts = ref_info["counts"]
            tar_counts = {str(k): int(v) for k, v in batch_df[col].value_counts().to_dict().items()}

            psi_score = compute_categorical_psi(ref_counts, tar_counts)
            chi2_res = compute_chi2_test(ref_counts, tar_counts)

            drift_status = "STABLE"
            if psi_score >= self.psi_alert:
                drift_status = "ALERT"
                drifted_count += 1
            elif psi_score >= self.psi_warning and chi2_res["p_value"] < self.p_value_threshold:
                drift_status = "ALERT"
                drifted_count += 1
            elif psi_score >= self.psi_warning:
                drift_status = "WARNING"
                warning_count += 1

            feature_reports[col] = {
                "feature_type": "categorical",
                "psi": round(psi_score, 4),
                "test_applied": "chi_square",
                "chi2_statistic": chi2_res["statistic"],
                "p_value": chi2_res["p_value"],
                "status": drift_status,
                "current_counts": tar_counts,
                "reference_counts": ref_counts,
            }

        # 3. Evaluate Prediction Drift if model provided
        prediction_drift = {}
        if model is not None and "prediction_stats" in self.reference_stats:
            ref_preds = np.array(self.reference_stats["prediction_stats"]["sample_distribution"])
            tar_preds = model.predict(batch_df)

            pred_psi = compute_numeric_psi(ref_preds, tar_preds)
            pred_ks = compute_ks_test(ref_preds, tar_preds)

            pred_status = "STABLE"
            if pred_psi >= self.psi_alert:
                pred_status = "ALERT"
            elif pred_psi >= self.psi_warning and pred_ks["p_value"] < self.p_value_threshold:
                pred_status = "ALERT"
            elif pred_psi >= self.psi_warning:
                pred_status = "WARNING"

            prediction_drift = {
                "psi": round(pred_psi, 4),
                "test_applied": "kolmogorov_smirnov",
                "ks_statistic": pred_ks["statistic"],
                "p_value": pred_ks["p_value"],
                "current_mean_prediction_min": round(float(np.mean(tar_preds)), 2),
                "reference_mean_prediction_min": self.reference_stats["prediction_stats"]["mean"],
                "status": pred_status,
            }

        total_features = len(feature_reports)
        overall_status = "STABLE"
        if drifted_count > 0 or (prediction_drift.get("status") == "ALERT"):
            overall_status = "ALERT"
        elif warning_count > 0 or (prediction_drift.get("status") == "WARNING"):
            overall_status = "WARNING"

        return {
            "batch_label": batch_label,
            "evaluated_at_utc": datetime.now(timezone.utc).isoformat(),
            "is_synthetic": is_synthetic,
            "sample_size": len(batch_df),
            "total_features_evaluated": total_features,
            "drifted_features_count": drifted_count,
            "warning_features_count": warning_count,
            "overall_status": overall_status,
            "thresholds": {
                "psi_warning": self.psi_warning,
                "psi_alert": self.psi_alert,
                "p_value_threshold": self.p_value_threshold,
            },
            "prediction_drift": prediction_drift,
            "features": feature_reports,
        }

    def save_reference_stats(self, output_path: str = "reports/monitoring/reference_stats.json") -> Path:
        """Save computed reference distribution statistics to a JSON file."""
        dest = Path(output_path)
        dest.parent.mkdir(parents=True, exist_ok=True)
        with open(dest, "w", encoding="utf-8") as f:
            json.dump(self.reference_stats, f, indent=2)
        return dest


def sample_clean_test_batch(
    test_df: pd.DataFrame,
    n_samples: int = 1500,
    random_state: int = 42,
) -> pd.DataFrame:
    """Draw a clean, unperturbed sample directly from the held-out test split.

    Args:
        test_df: Held-out test features dataframe.
        n_samples: Number of rows to sample.
        random_state: Seed for reproducible sampling.

    Returns:
        Sampled DataFrame representing normal operational data.
    """
    n = min(len(test_df), n_samples)
    return test_df.sample(n=n, random_state=random_state).reset_index(drop=True)


def generate_synthetic_drift_batch(
    base_df: pd.DataFrame,
    n_samples: int = 1500,
    random_state: int = 42,
) -> pd.DataFrame:
    """Generate a realistic, synthetically shifted data batch for drift testing.

    What this simulates in real-world delivery operations:
    1. Severe Weather / Monsoon Detour Shift:
       - Delivery distance effectively increases (+2.5 standard deviations).
    2. Festival Surge:
       - Orders during festival seasons spike significantly (`Festival_Yes` proportion jumps from ~2% to ~45%).
    3. Late Night Peak Congestion:
       - `order_hour` clusters heavily into late night delivery hours (+1.8 standard deviations).

    CRITICAL NOTE: This data is explicitly flagged as SYNTHETIC for demonstration purposes.

    Args:
        base_df: Source dataframe to derive shifted features from.
        n_samples: Number of rows to generate.
        random_state: Reproducibility seed.

    Returns:
        Perturbed DataFrame clearly exhibiting statistical distribution drift.
    """
    rng = np.random.default_rng(random_state)
    n = min(len(base_df), n_samples)
    sampled = base_df.sample(n=n, random_state=random_state).copy().reset_index(drop=True)

    # 1. Shift continuous delivery distance (simulate monsoon detours / suburban expansion)
    if "num__distance_km" in sampled.columns:
        sampled["num__distance_km"] += rng.normal(loc=2.5, scale=0.6, size=n)

    # 2. Shift order hour towards late-night rush (21:00 - 23:00)
    if "num__order_hour" in sampled.columns:
        sampled["num__order_hour"] += rng.normal(loc=1.8, scale=0.5, size=n)

    # 3. Shift festival categorical proportions
    if "cat__Festival_Yes" in sampled.columns and "cat__Festival_No" in sampled.columns:
        flip_mask = rng.random(size=n) < 0.45
        sampled.loc[flip_mask, "cat__Festival_Yes"] = 1.0
        sampled.loc[flip_mask, "cat__Festival_No"] = 0.0

    return sampled
